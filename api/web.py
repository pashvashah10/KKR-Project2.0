@router.get("/checkout", response_class=HTMLResponse)
def checkout_page(request: Request) -> HTMLResponse:
    cart = checkout.read_cart(request.session)
    if not cart:
        return RedirectResponse("/cart", status_code=303)  # type: ignore[return-value]
    return render(request, "checkout.html", weather="clear")


@router.post("/checkout")
async def place(
    request: Request,
    billing_name: str = Form(...),
    billing_email: str = Form(...),
    billing_company: str = Form(""),
    billing_address: str = Form(""),
) -> RedirectResponse:
    cart = checkout.read_cart(request.session)
    if not cart:
        return RedirectResponse("/cart", status_code=303)

    account = guest_account(request, email=billing_email.strip(), name=billing_name.strip())
    order = checkout.place_order(
        account, cart,
        {
            "name": billing_name.strip()[:200],
            "email": billing_email.strip()[:200],
            "company": billing_company.strip()[:200],
            "address": billing_address.strip()[:500],
        },
    )
    checkout.fulfil(order, submit_fit)
    checkout.clear_cart(request.session)
    request.session["last_order"] = order["id"]
    return RedirectResponse(f"/orders/{order['id']}", status_code=303)


@router.get("/orders/{order_id}", response_class=HTMLResponse)
def order_page(request: Request, order_id: str) -> HTMLResponse:
    account = current_account(request)
    if account is None:
        raise HTTPException(404, "No such order.")
    order = store.get_order(order_id, account_id=account["id"])
    if order is None:
        raise HTTPException(404, "No such order.")
    return render(
        request, "order.html",
        order=checkout.order_view(order),
        just_placed=request.session.pop("last_order", None) == order_id,
        weather="clear",
    )


@router.get("/account", response_class=HTMLResponse)
def account_page(request: Request) -> HTMLResponse:
    account = current_account(request)
    if account is None:
        return render(request, "account.html", orders=[], sites=[], subs=[], weather="cloud")

    sites = [s for s in store.list_sites(account["id"]) if not s.get("is_example")]
    for s in sites:
        s["station"] = _station_view(s)
        s["job"] = store.latest_job(s["id"])
    return render(
        request, "account.html",
        orders=[checkout.order_view(o) for o in store.list_orders(account["id"])],
        sites=sites,
        subs=store.list_subscriptions(account["id"]),
        weather="cloud",
    )


@router.post("/account/subscriptions/{sub_id}/cancel")
async def cancel_sub(request: Request, sub_id: str) -> RedirectResponse:
    account = current_account(request)
    if account:
        store.cancel_subscription(sub_id, account["id"])
    return RedirectResponse("/account", status_code=303)
