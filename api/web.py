@router.post("/cart/add")
async def cart_add(
    request: Request,
    slug: str = Form(...),
    quantity: int = Form(1),
    site_id: str | None = Form(None),
    site_name: str | None = Form(None),
    premium_cents: int | None = Form(None),
    peril_id: str | None = Form(None),
    year: int | None = Form(None),
) -> RedirectResponse:
    product = catalog.get(slug)
    if product is None:
        raise HTTPException(404, "No such service.")

    config: dict[str, Any] = {}
    if product.is_quoted:
        # A quoted line carries the engine's own number. Recomputed server-side
        # rather than trusted from the form, so a edited field cannot set a price.
        if not site_id:
            raise HTTPException(400, "A quoted service needs a venue.")
        site = store.get_site(site_id)
        if site is None or site["status"] != "ready":
            raise HTTPException(409, "That venue is not fitted yet.")
        priced = _indicative(site)
        if not priced or not priced.get("available"):
            raise HTTPException(409, "No indicative price is available for that venue.")
        config = {
            "premium_cents": priced["premium_cents"],
            "peril": priced["terms"]["peril"],
            "peril_id": priced["terms"]["peril_id"],
            "year": priced["terms"]["year"],
            "attachment_days": priced["terms"]["attachment_days"],
            "payout_per_day": priced["terms"]["payout_per_day"],
            "limit": priced["terms"]["limit"],
            "indicative": True,
        }
        site_name = site["name"]

    checkout.add_line(
        request.session, slug, quantity=quantity,
        site_id=site_id or None, site_name=site_name, config=config,
    )
    return RedirectResponse("/cart", status_code=303)


