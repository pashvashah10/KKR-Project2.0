"""The storefront: real URLs, server-rendered, with a cart.

Separate from `/v1` on purpose. The JSON API is what a customer's engineers
integrate against; this is what their finance director browses. Sharing a router
would mean the pages inherit bearer-token auth and the API inherits session
cookies, and both would be wrong.

### Why server-rendered

A storefront needs shareable links, a working back button, and a page that means
something before JavaScript runs. A cart with four line items does not justify a
client-side router. The only JavaScript that matters here is the job poller on
`/configure`, and that is genuinely asynchronous work rather than a rendering
strategy.

### Identity

A visitor gets a guest account on first write. That is a real `accounts` row
with a real API key, created lazily, so an order always has an owner and the
same person can later be sent a magic link back into their own work. Nothing
asks them to register before they can see a price.

### The latency problem, and the shape it forces

Fitting a century at a new coordinate is 80-140 seconds. That cannot happen
inside a request, so `POST /configure/{slug}/venue` starts a job and returns
`{"job_id", "status_url"}` immediately; the page polls. Anyone who does not want
to sit and watch can leave an email address and be sent a link back to the
finished quote.
"""

